#!/usr/bin/env python3
"""Generate lib/src/design_system/icons/vnlf_lucide.dart from lucide-static.

The website draws its icons with lucide-react 0.468.0. The app embeds the
same outlines, read from the matching lucide-static package's
icon-nodes.json, so icons look the same without a font or a new dependency.
Add a name to ICONS and rerun to make another icon available.

Usage: python3 tool/sync_lucide_icons.py <extracted lucide-static/package>
"""

from __future__ import annotations

import argparse
import html
import json
import pathlib
import shutil
import subprocess

VERSION = '0.468.0'
OUT = pathlib.Path('lib/src/design_system/icons/vnlf_lucide.dart')

# Icons the ported screens use, by their lucide (kebab-case) name.
ICONS = [
    'arrow-big-down', 'arrow-big-up', 'arrow-left', 'arrow-up-right', 'bell',
    'book-open', 'bookmark', 'check', 'chevron-down', 'chevron-left',
    'chevron-right', 'circle-check', 'circle-help', 'compass', 'ellipsis',
    'eye', 'flag', 'flame', 'folder-git-2', 'headphones', 'image-plus',
    'layout-grid', 'link-2', 'log-out', 'mail', 'message-circle',
    'message-square-text', 'mic-vocal', 'monitor', 'moon', 'pen-line', 'pin',
    'play', 'plus', 'radio', 'refresh-cw', 'reply', 'rotate-ccw', 'search',
    'send', 'settings', 'shield-check', 'square-plus', 'sticker', 'store',
    'sun', 'trash-2', 'trophy', 'user-check', 'user-plus', 'users', 'x', 'zap',
]


def dart_name(icon: str) -> str:
    head, *rest = icon.split('-')
    return head + ''.join(part[:1].upper() + part[1:] for part in rest)


def element(tag: str, attributes: dict) -> str:
    attrs = ''.join(f' {name}="{html.escape(str(value), quote=True)}"'
                    for name, value in attributes.items() if name != 'key')
    return f'<{tag}{attrs}/>'


def generate(nodes: dict, license_text: str, icons: list[str]) -> str:
    missing = [icon for icon in icons if icon not in nodes]
    if missing:
        raise ValueError(f'lucide-static {VERSION} has no icon {missing}')
    license_comment = '\n'.join(f'// {line}'.rstrip()
                                for line in license_text.strip().splitlines())
    lines = [
        '// GENERATED by `python3 tool/sync_lucide_icons.py` from',
        f'// lucide-static {VERSION}, the icon set the website uses. Do not edit.',
        '//',
        license_comment,
        '',
        '/// Lucide outlines (24×24 view box) drawn by [VnlfIcon].',
        'enum VnlfLucide {',
    ]
    for icon in sorted(icons):
        body = ''.join(element(tag, attrs) for tag, attrs in nodes[icon])
        escaped = body.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
        lines.append(f"  {dart_name(icon)}('{escaped}'),")
    lines[-1] = lines[-1][:-1] + ';'
    lines += [
        '',
        '  const VnlfLucide(this.body);',
        '',
        '  /// The SVG child elements of the icon.',
        '  final String body;',
        '}',
        '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('package', help='extracted lucide-static package dir')
    args = parser.parse_args()
    package = pathlib.Path(args.package)
    meta = json.loads((package / 'package.json').read_text(encoding='utf-8'))
    if meta.get('version') != VERSION:
        raise SystemExit(f'expected lucide-static {VERSION}, '
                         f'found {meta.get("version")}')
    nodes = json.loads((package / 'icon-nodes.json').read_text(encoding='utf-8'))
    license_text = (package / 'LICENSE').read_text(encoding='utf-8')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generate(nodes, license_text, ICONS), encoding='utf-8')
    if dart := shutil.which('dart'):
        subprocess.run([dart, 'format', str(OUT)], check=True,
                       stdout=subprocess.DEVNULL)


if __name__ == '__main__':
    main()
